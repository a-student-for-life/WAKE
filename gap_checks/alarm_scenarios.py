"""Alarm burden as a scenario with ranges (DEVIATIONS.md 10).

Exploratory and descriptive; added after the results in answer to the 15 Nov 2026 review,
which asked that the alarm burden be presented as a scenario under stated assumptions.
Extends gap_checks/alarm_burden.py (its central scenario is unchanged).

usage: python3 -I gap_checks/alarm_scenarios.py   (from the repository root)
writes results/gap_checks/alarm_scenarios.csv and results/gap_checks/alarm_scenarios.md

Alarms per incident vessel flagged = (alarm share x fleet x 365) / (incident flag rate x incidents
per year). Assumptions varied one at a time and then together:
- fleet: median fleet_n (15,507), its 10th and 90th percentiles over the 265 fleet days;
- incidents per year: 113 (1,247 combined-table incidents / 11 years) or 4,170 (all 45,865 NRC
  reports involving a vessel / 11 years, a deliberately generous upper bound that treats every
  vessel report as an event to catch);
- incident flag rate: measured, or the upper end of its Wilson 95% interval.
The scenario-free comparison is the lift: incident flag rate / control flag rate, i.e. how
much more often an alarm falls on an incident vessel than on a matched vessel of the same
type and exposure.
"""
import glob

import numpy as np
import pandas as pd

N_SETS = 197
fleet = pd.concat(pd.read_csv(f, usecols=["fleet_day", "fleet_n"]).drop_duplicates()
                  for f in glob.glob("data/stage_b/windows/*_real.csv.gz")).drop_duplicates()
F = {"low": fleet.fleet_n.quantile(.1), "central": fleet.fleet_n.median(), "high": fleet.fleet_n.quantile(.9)}
INC = {"central": 1247 / 11, "generous": 45865 / 11}


def wilson_hi(p, n, z=1.96):
    c = p + z * z / (2 * n)
    return (c + z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / (1 + z * z / n)


fr = pd.read_csv("results/stageB/tables/flag_rates.csv")
g = pd.read_csv("results/gtn/tables/flag_rates.csv").iloc[0]
rows = []
for r in fr.itertuples():
    rows.append((r.detector, r.top, float(r.top.rstrip("%")) / 100, r.inc_flagged, r.ctrl_flagged, N_SETS))
rows.append(("d7_gtn", "NFA<1e-9", g.ctrl_flagged, g.inc_flagged, g.ctrl_flagged, int(g.n_sets)))
out = []
for det, lvl, share, pinc, pctl, n in rows:
    hi = wilson_hi(pinc, n)

    def burden(fl, inc_y, p):
        return share * fl * 365 / (p * inc_y) if p > 0 else np.inf

    out.append(dict(detector=det, alarm_level=lvl, alarms_per_day=share * F["central"],
                    incident_flag_rate=pinc, control_flag_rate=pctl,
                    lift=pinc / pctl if pctl > 0 else np.nan,
                    central=burden(F["central"], INC["central"], pinc),
                    fleet_low=burden(F["low"], INC["central"], pinc),
                    fleet_high=burden(F["high"], INC["central"], pinc),
                    flag_rate_wilson_hi=burden(F["central"], INC["central"], hi),
                    incidents_generous=burden(F["central"], INC["generous"], pinc),
                    most_favourable=burden(F["low"], INC["generous"], hi)))
o = pd.DataFrame(out)
o.to_csv("results/gap_checks/alarm_scenarios.csv", index=False)

L = ["# Alarm burden scenarios\n",
     "Exploratory (DEVIATIONS.md 10). Generated by `gap_checks/alarm_scenarios.py`. Alarms per "
     "incident vessel flagged; GeoTrackNet's control flag rate stands in for its national rate.\n",
     f"Fleet per day: 10th percentile {F['low']:,.0f}, median {F['central']:,.0f}, 90th percentile "
     f"{F['high']:,.0f}. Incidents per year: {INC['central']:.0f} (combined table) or "
     f"{INC['generous']:,.0f} (every NRC report involving a vessel).\n",
     "| Detector | Level | Lift (incident / control flag rate) | Central | Fleet 10th-90th pct | "
     "Flag rate at Wilson upper bound | Every NRC vessel report | All favourable together |",
     "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for r in o.itertuples():
    L.append(f"| {r.detector} | {r.alarm_level} | {r.lift:.2f} | {r.central:,.0f} | "
             f"{r.fleet_low:,.0f}-{r.fleet_high:,.0f} | {r.flag_rate_wilson_hi:,.0f} | "
             f"{r.incidents_generous:,.0f} | {r.most_favourable:,.0f} |")
open("results/gap_checks/alarm_scenarios.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
