"""GeoTrackNet and the simple detectors by GeoTrackNet region (DEVIATIONS.md 10).

Exploratory and descriptive, added after the results in answer to the 15 Nov 2026 review.
Per region: sets in the GeoTrackNet main test, the pooled AUC of GeoTrackNet and of each
simple detector on the same sets (window main), and the region's training outcome.
Per-set ranks come from results/gtn/tables/ranks_main.csv and
results/stageB/tables/ranks_main.csv (rank01 = share of controls scoring below the incident
vessel, ties half), so the pooled AUC of a region is sum(rank01 x controls) / sum(controls).
Simple-detector ranks use all of a set's controls, GeoTrackNet's only the scored ones, so
this is the "same sets" comparison, not "same vessels".

usage: python3 -I gap_checks/gtn_by_region.py   (from the repository root)
writes results/gap_checks/gtn_by_region.csv and .md
"""
import pandas as pd

g = pd.read_csv("results/gtn/tables/ranks_main.csv")
s = pd.read_csv("results/stageB/tables/ranks_main.csv")
reg = pd.read_csv("data/gtn/regions.csv")
tr = pd.read_csv("results/gtn/tables/training.csv").set_index("region")
DN = {"d1_speed_drop": "Speed drop", "d2_loiter_h": "Loitering", "d3_gap_ratio": "AIS gap",
      "d4_off_lane": "Off-lane", "d5_iforest": "Isolation Forest"}


def pooled(d):
    return (d.rank01 * d.n_controls).sum() / d.n_controls.sum()


rows = []
for r, gg in list(g.groupby("region")) + [("All", g)]:
    row = dict(region=r, sets=len(gg), controls_scored=int(gg.n_controls.sum()), gtn=pooled(gg))
    ss = s[s.set_id.isin(gg.set_id)]
    for d, n in DN.items():
        row[n] = pooled(ss[ss.detector == d])
    if r != "All":
        q = reg.set_index("region").loc[r]
        row["box"] = f"{q.lat_min:g}-{q.lat_max:g}N, {abs(q.lon_max):g}-{abs(q.lon_min):g}W"
        row["train_tracks"] = int(tr.loc[r, "n_valid_tracks"])
        row["stop"] = "max steps" if "max" in tr.loc[r, "status"] else (
            "overfit, best checkpoint" if r in ("R14", "R15") else "converged")
    rows.append(row)
o = pd.DataFrame(rows)
o.to_csv("results/gap_checks/gtn_by_region.csv", index=False)
L = ["# GeoTrackNet by region (window main, same sets)\n",
     "Exploratory (DEVIATIONS.md 10). Generated by `gap_checks/gtn_by_region.py`. Pooled AUC per region; "
     "regions with few sets are noisy and are shown for completeness, not tested.\n",
     "| Region | Box | Training tracks | Training stop | Sets | GeoTrackNet | " + " | ".join(DN.values()) + " |",
     "| --- | --- | --- | --- | --- | --- |" + " --- |" * len(DN)]
for _, r in o.iterrows():
    L.append(f"| {r.region} | {r['box'] if isinstance(r['box'], str) else ''} | "
             f"{'' if pd.isna(r.train_tracks) else int(r.train_tracks)} | {r['stop'] if isinstance(r['stop'], str) else ''} | "
             f"{r.sets} | {r.gtn:.2f} | " + " | ".join(f"{r[n]:.2f}"
                                                     for n in DN.values()) + " |")
open("results/gap_checks/gtn_by_region.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
