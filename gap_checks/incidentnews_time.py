"""IncidentNews report-time sensitivity (DEVIATIONS.md 10).

IncidentNews records carry a date only. The main analysis sets T to local midnight at the
start of that date (T_rule in_midnight_*), so the 24-hour window is the day before the
incident date. Asked by the 15 Nov 2026 review, this check moves T to local noon of the
incident date for those events (real dates only), rebuilds the windows with the unchanged
stage_b/windows.py, rematches with the unchanged M4 rule and recomputes the AUCs.
Exploratory and descriptive, added after all results were known.

usage (from the repository root):
  python3 -I gap_checks/incidentnews_time.py windows [--max-minutes M]   # downloads AIS, resumable
  python3 -I gap_checks/incidentnews_time.py analyse
outputs: data/gap_checks/in_noon/ (events, windows, state, matched sets) and
         results/gap_checks/incidentnews_time.csv / .md
"""
import os
import sys
from datetime import datetime, timedelta

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "stage_b"))
D = os.path.join(ROOT, "data", "gap_checks", "in_noon")
EV = os.path.join(D, "events.csv")
SHIFT_H = 12


def build_events():
    ev = pd.read_csv(os.path.join(ROOT, "data", "stage_b", "events.csv"), dtype={"mmsis": str, "imo": str})
    keep = ev[ev.T_rule.str.startswith("in_midnight") & (ev.main_exclude.astype(str).str.lower() == "false")].copy()
    for c in ("T_real", "T_utc"):
        keep[c] = [(datetime.strptime(t, "%Y-%m-%d %H:%M") + timedelta(hours=SHIFT_H)).strftime("%Y-%m-%d %H:%M")
                   for t in keep[c]]
    keep["T_rule"] = keep.T_rule + "_plus12h"
    os.makedirs(D, exist_ok=True)
    keep.to_csv(EV, index=False)
    return keep


def windows(argv):
    import windows as W
    if not os.path.exists(EV):
        build_events()
    W.EVENTS = EV
    W.OUTDIR = os.path.join(D, "windows")
    W.STATE = os.path.join(D, "state.json")
    W.SCEN = ["real"]
    sys.argv = [sys.argv[0], "--no-git"] + argv
    W.main()


def analyse():
    import glob

    import analyse as A
    import match as M
    ev = pd.read_csv(EV)
    rows, sets = [], []
    for f in sorted(glob.glob(os.path.join(D, "windows", "*.csv.gz"))):
        d = pd.read_csv(f, usecols=M.COLS)
        d = M.add_logs(d[d.window == "main"])
        s, r = M.match_one(d, "M4")
        sets.append(dict(event_id=int(d.event_id.iloc[0]), status="matched" if s is not None else r))
        if s is not None:
            rows.append(s)
    noon = pd.concat(rows, ignore_index=True)
    noon.to_csv(os.path.join(D, "M4_noon.csv.gz"), index=False, compression={"method": "gzip", "mtime": 0})
    S = pd.DataFrame(sets)
    orig = pd.read_csv(os.path.join(ROOT, "data", "stage_b", "matched", "M4.csv.gz"))
    orig = orig[(orig.scenario == "real") & orig.event_id.isin(ev.event_id)]
    w0 = A.load_windows()
    old_files = glob.glob(os.path.join(D, "windows", "*.csv.gz"))
    w1 = pd.concat([pd.read_csv(f, usecols=A.WCOLS) for f in old_files], ignore_index=True)
    w1["candidate_excluded"] = w1.candidate_excluded.astype(bool)
    w1["is_incident"] = w1.is_incident.astype(bool)
    both = set(orig.event_id) & set(noon.event_id)
    out = []
    for lab, mm, ww, ids in [("Midnight (as analysed), all IncidentNews sets", orig, w0, set(orig.event_id)),
                             ("Noon, all sets matched at noon", noon, w1, set(noon.event_id)),
                             ("Midnight, events matched at both times", orig, w0, both),
                             ("Noon, events matched at both times", noon, w1, both)]:
        for window in ("main", "early3"):
            mem = A.members_for(mm[mm.event_id.isin(ids)], ww, window)
            for det in A.DET:
                r = A.auc_test(A.set_arrays(mem, det), perm=False)
                r.update(label=lab, window=window, detector=det)
                out.append(r)
    o = pd.DataFrame(out)
    o.to_csv(os.path.join(ROOT, "results", "gap_checks", "incidentnews_time.csv"), index=False)
    L = ["# IncidentNews report time: local midnight against local noon\n",
         f"Exploratory (DEVIATIONS.md 10). Generated by `gap_checks/incidentnews_time.py`. "
         f"IncidentNews events in the main analysis with a date-only time: {len(ev)}; window files "
         f"built at noon: {len(old_files)}; matched at noon: {(S.status == 'matched').sum()} "
         f"(midnight: {orig.event_id.nunique()}; both: {len(both)}).\n",
         f"Noon sets not matched: {S[S.status != 'matched'].status.value_counts().to_dict()}\n",
         "| Timing | Window | Sets | " + " | ".join(A.DNAME[d] for d in A.DET) + " |",
         "| --- | --- | --- |" + " --- |" * len(A.DET)]
    for (lab, win), g in o.groupby(["label", "window"], sort=False):
        g = g.set_index("detector")
        L.append(f"| {lab} | {win} | {int(g.n_sets.iloc[0])} | " + " | ".join(
            f"{g.auc[d]:.3f} ({g.lo[d]:.3f}-{g.hi[d]:.3f})" for d in A.DET) + " |")
    open(os.path.join(ROOT, "results", "gap_checks", "incidentnews_time.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    os.chdir(ROOT)
    {"windows": lambda: windows(sys.argv[2:]), "analyse": analyse}[sys.argv[1]]()
