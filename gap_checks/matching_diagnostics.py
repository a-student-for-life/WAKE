"""Matching diagnostics asked for in the 15 Nov 2026 review (DEVIATIONS.md 10).

Exploratory and descriptive; added after all results were known. Nothing here changes the
main test.

usage: python3 -I gap_checks/matching_diagnostics.py   (from the repository root)
writes results/gap_checks/matching_diagnostics.md and
       results/gap_checks/matching_auc_checks.csv

1. Set sizes, matching distances and radius (50 km or widened to 150 km) of the 197 main
   sets (M4, real dates, main sample).
2. Balance of the incident vessels and their controls on the matching variables plus
   distance from the incident centre (not a matching variable).
3. Control reuse: vessels serving as a control in more than one set, and vessels that are
   an incident vessel in one set and a control in another.
4. AUC with a bootstrap that resamples clusters of sets linked by a shared vessel, so
   reuse is not treated as independence.
5. AUC with each reused vessel kept only in its first set (by event id).
6. Radius: sets matched within 50 km only, sets widened to 150 km, and M3 (all sets on the
   whole 150 km box, same type), on the same 197 events where matched.
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "stage_b"))
import analyse as A  # noqa: E402

SEED = 20261115
NBOOT = 5000
OUT_MD = "results/gap_checks/matching_diagnostics.md"
OUT_CSV = "results/gap_checks/matching_auc_checks.csv"

ev = pd.read_csv("data/stage_b/events.csv")
ev["main_exclude"] = ev.main_exclude.astype(str).str.lower() == "true"
main_ids = set(ev.event_id[~ev.main_exclude])
M4 = pd.read_csv("data/stage_b/matched/M4.csv.gz")
M3 = pd.read_csv("data/stage_b/matched/M3.csv.gz")
m = M4[(M4.scenario == "real") & M4.event_id.isin(main_ids)].copy()
assert m.event_id.nunique() == 197
w = A.load_windows()
L = []


def smd(a, b):
    a, b = a.dropna(), b.dropna()
    return (a.mean() - b.mean()) / np.sqrt((a.var() + b.var()) / 2)


# 1. set sizes, distances, radius --------------------------------------------------------
sets = m.groupby("event_id").agg(radius=("radius_km", "first"),
                                 n_controls=("role", lambda s: (s == "control").sum()))
ctrl = m[m.role == "control"]
inc = m[m.role == "incident"]
L.append("# Matching diagnostics (M4, real dates, 197 main sets)\n")
L.append("Exploratory, added after the results (DEVIATIONS.md 10). "
         "Generated by `gap_checks/matching_diagnostics.py`.\n")
L.append("## Sets\n")
L.append(f"- Sets: {len(sets)}; controls per set: median {sets.n_controls.median():.0f}, "
         f"range {sets.n_controls.min()}-{sets.n_controls.max()}; control rows {len(ctrl)}.")
L.append(f"- Matched within 50 km: {(sets.radius == 50).sum()}; widened to the 150 km box "
         f"because fewer than 10 same-type vessels were within 50 km: {(sets.radius == 150).sum()}.")
q = ctrl.distance.quantile([.25, .5, .75, .9, 1]).round(2).tolist()
L.append(f"- Mahalanobis matching distance of controls: quartiles {q[0]}, {q[1]}, {q[2]}; "
         f"90th percentile {q[3]}; maximum {q[4]}.")
fd = ctrl.groupby("event_id").distance.max()
L.append(f"- Largest control distance per set: median {fd.median():.2f}, "
         f"90th percentile {fd.quantile(.9):.2f}; sets with a control farther than 10: "
         f"{(fd > 10).sum()} (event ids {', '.join(map(str, fd.index[fd > 10]))}). Large values arise "
         f"when the incident vessel differs from most of its pool in hours heard or length while the "
         f"pool varies little on that variable, which inflates the Mahalanobis scale.\n")

# 2. balance -------------------------------------------------------------------------------
L.append("## Balance (incident vessels against their controls)\n")
L.append("| Variable | Incident median | Control median | SMD |")
L.append("| --- | --- | --- | --- |")
bal = []
for name, f in [("AIS positions in window", lambda d: d.n_pos),
                ("Hours heard", lambda d: d.hours),
                ("Length (m)", lambda d: d.length_m.where(d.length_m > 0)),
                ("Distance from incident centre (km)", lambda d: d.dist_centre_km)]:
    a, b = f(inc), f(ctrl)
    la, lb = (np.log1p(a), np.log1p(b)) if name != "Distance from incident centre (km)" else (a, b)
    s = smd(la, lb)
    bal.append((name, a.median(), b.median(), s))
    L.append(f"| {name} | {a.median():.1f} | {b.median():.1f} | {s:.3f} |")
L.append("\nSMD on log(1 + x) for positions, hours and length, raw km for distance. Type group "
         "is matched exactly. Distance from the centre is 0 by construction for most incident "
         "vessels when the centre is their own position, so it is shown, not balanced.\n")
for st in sorted(sets.radius.unique()):
    ids = sets.index[sets.radius == st]
    c = ctrl[ctrl.event_id.isin(ids)]
    L.append(f"- Sets with radius {st:.0f} km: control distance from centre median "
             f"{c.dist_centre_km.median():.1f} km (IQR {c.dist_centre_km.quantile(.25):.1f}-"
             f"{c.dist_centre_km.quantile(.75):.1f}).")
L.append("")

# 3. reuse -----------------------------------------------------------------------------------
cc = ctrl.groupby("mmsi").event_id.nunique()
inc_mmsi = set(inc.mmsi)
both = inc_mmsi & set(ctrl.mmsi)
ic = inc.groupby("mmsi").event_id.nunique()
L.append("## Reuse of vessels across sets\n")
L.append(f"- Distinct control vessels: {len(cc)} for {len(ctrl)} control rows; "
         f"{(cc > 1).sum()} vessels are controls in more than one set "
         f"(max {cc.max()} sets); rows belonging to reused vessels: "
         f"{ctrl.mmsi.isin(cc.index[cc > 1]).sum()}.")
L.append(f"- Incident vessels in more than one event: {(ic > 1).sum()}; vessels that are an "
         f"incident vessel in one set and a control in another: {len(both)}.")

# cluster sets linked by any shared vessel (union-find)
parent = {e: e for e in sets.index}


def find(x):
    while parent[x] != x:
        parent[x] = parent[parent[x]]
        x = parent[x]
    return x


for _, g in m.groupby("mmsi"):
    es = g.event_id.unique()
    for e in es[1:]:
        parent[find(e)] = find(es[0])
clus = pd.Series({e: find(e) for e in sets.index})
cs = clus.value_counts()
L.append(f"- Linking sets that share any vessel gives {len(cs)} clusters for 197 sets; "
         f"largest cluster {cs.max()} sets; {(cs == 1).sum()} sets share no vessel with any other.\n")

# 4/5/6. AUC checks ---------------------------------------------------------------------
rows = []


def run(matched, label, ids=None, cluster=None):
    mm = matched[(matched.scenario == "real") & matched.event_id.isin(ids if ids is not None else main_ids)]
    mem = A.members_for(mm, w, "main")
    for d in A.DET:
        s = A.set_arrays(mem, d)
        r = A.auc_test(s, perm=False, boot=cluster is None)
        if cluster is not None:
            ev_of = np.array([int(x[0].split("_")[0]) for x in s])
            wobs = np.array([x[1][x[2]] for x in s])
            npr = np.array([x[3] for x in s], float)
            lab = cluster.reindex(ev_of).to_numpy()
            ul = np.unique(lab)
            groups = [np.where(lab == u)[0] for u in ul]
            gw = np.array([wobs[g].sum() for g in groups])
            gn = np.array([npr[g].sum() for g in groups])
            rng = np.random.default_rng(SEED)
            idx = rng.integers(0, len(groups), (NBOOT, len(groups)))
            b = gw[idx].sum(1) / gn[idx].sum(1)
            r["lo"], r["hi"] = np.percentile(b, [2.5, 97.5])
        r.update(detector=d, label=label)
        rows.append(r)


run(M4, "Main (M4), set bootstrap as reported")
run(M4, "Main (M4), cluster bootstrap (sets sharing a vessel resampled together)", cluster=clus)
# first-use only
first = (m[m.role == "control"].sort_values("event_id").drop_duplicates("mmsi"))
keep = pd.concat([m[m.role == "incident"], first])
keep = keep[~((keep.role == "control") & keep.mmsi.isin(inc_mmsi))]
run(keep, "Each vessel used once (later reuse and incident vessels dropped as controls)")
run(M4, "Sets with a control farther than 10 dropped", ids=set(fd.index[fd <= 10]))
run(M4, "Radius 50 km only (sets not widened)", ids=set(sets.index[sets.radius == 50]))
run(M4, "Widened to 150 km only", ids=set(sets.index[sets.radius == 150]))
run(M3, "M3: every set on the whole 150 km box", ids=set(sets.index))
out = pd.DataFrame(rows)
out.to_csv(OUT_CSV, index=False)

L.append("## AUC checks (window main)\n")
L.append("| Check | Sets | " + " | ".join(A.DNAME[d] for d in A.DET) + " |")
L.append("| --- | --- |" + " --- |" * len(A.DET))
for lab, g in out.groupby("label", sort=False):
    g = g.set_index("detector")
    L.append(f"| {lab} | {int(g.n_sets.iloc[0])} | " + " | ".join(
        f"{g.auc[d]:.3f} ({g.lo[d]:.3f}-{g.hi[d]:.3f})" for d in A.DET) + " |")
L.append("\nAUC with 95% bootstrap interval (5,000 resamples). No permutation tests: these are "
         "descriptive checks, not new hypotheses.")
open(OUT_MD, "w").write("\n".join(L) + "\n")
print("\n".join(L))
