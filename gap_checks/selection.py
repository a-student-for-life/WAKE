"""Selection and attrition from the 1,247 incidents to the 197 matched sets (DEVIATIONS.md 10).

Exploratory and descriptive; added after the results, in answer to the 15 Nov 2026 review.

usage: python3 -I gap_checks/selection.py   (from the repository root)
writes results/gap_checks/selection.md and results/gap_checks/selection_stages.csv

Each incident in data/incidents.csv is placed at the furthest stage it reached:
  A  no AIS name candidate within the two scanned days
  B  candidate(s), all auto-rejected beyond 100 km
  C  reviewed, no confirmed match
  D  confirmed, event excluded from the main analysis (berth, storm or not the source)
  E  confirmed, in the main analysis, no matched set (too few positions or too few controls)
  F  in a matched set (the 197 events)
Incidents merged into one vessel event share that event's stage. Stages are compared on
source, year, setting, incident type, reported vessel type and region.
"""
import pandas as pd

inc = pd.read_csv("data/incidents.csv")
cand = pd.read_csv("data/candidates.csv")
conf = pd.read_csv("data/confirmed.csv")
ev = pd.read_csv("data/stage_b/events.csv")
ev["main_exclude"] = ev.main_exclude.astype(str).str.lower() == "true"
sets = pd.read_csv("data/stage_b/matched/sets.csv")
s4 = sets[(sets.definition == "M4") & (sets.scenario == "real")].set_index("event_id")

stage = pd.Series("A no AIS candidate", index=inc.incident_id)
stage[stage.index.isin(cand.incident_id)] = "B candidates all beyond 100 km"
stage[stage.index.isin(cand.incident_id[cand.auto_reject.isna()])] = "C reviewed, not confirmed"
stage[stage.index.isin(conf.incident_id)] = "D confirmed, excluded from main"
reason = pd.Series("", index=inc.incident_id)
for r in ev.itertuples():
    ids = str(r.incident_ids).split(";") if ";" in str(r.incident_ids) else str(r.incident_ids).split(",")
    ids = [x.strip() for x in ids if x.strip()]
    if r.main_exclude:
        st = "D confirmed, excluded from main"
    elif s4.loc[r.event_id, "status"] == "matched":
        st = "F matched set (analysed)"
    else:
        st = "E main, no matched set"
        reason[reason.index.isin(ids)] = s4.loc[r.event_id, "status"]
    stage[stage.index.isin(ids)] = st
inc["stage"] = inc.incident_id.map(stage)
inc["reason"] = inc.incident_id.map(reason)
assert inc.stage.notna().all()

REG = {"AK": "Alaska", "WA": "Pacific NW", "OR": "Pacific NW", "CA": "California", "HI": "Hawaii/Pacific",
       "GU": "Hawaii/Pacific", "AS": "Hawaii/Pacific", "MP": "Hawaii/Pacific",
       "TX": "Gulf", "LA": "Gulf", "MS": "Gulf", "AL": "Gulf", "FL": "Florida",
       "MI": "Great Lakes", "WI": "Great Lakes", "MN": "Great Lakes", "OH": "Great Lakes",
       "IL": "Great Lakes", "IN": "Great Lakes", "PR": "Caribbean", "VI": "Caribbean"}
inc["region"] = inc.state.map(REG).fillna(inc.state.map(
    lambda s: "Atlantic" if s in {"ME", "NH", "MA", "RI", "CT", "NY", "NJ", "DE", "MD", "VA", "NC",
                                  "SC", "GA", "PA", "DC"} else "Inland/other"))
VT = {"FISHING": "Fishing", "TUG": "Tug/tow", "TOW BOAT": "Tug/tow", "TANKER": "Tanker",
      "FREIGHT DRY-BULK": "Cargo", "FREIGHT": "Cargo", "CONTAINER": "Cargo",
      "RORO (ROLL-ON ROLL-OFF)": "Cargo", "CRUISE": "Passenger", "FERRY": "Passenger"}
inc["vtype"] = inc.vessel_type_reported.map(VT).fillna(
    inc.vessel_type_reported.map(lambda v: "Not given (IncidentNews has no type field)" if pd.isna(v) else "Other"))
inc["years"] = pd.cut(pd.to_datetime(inc.date_local).dt.year, [2014, 2018, 2021, 2025],
                      labels=["2015-2018", "2019-2021", "2022-2025"])
inc[["incident_id", "stage", "reason", "source", "region", "vtype", "years", "setting",
     "incident_type"]].to_csv("results/gap_checks/selection_stages.csv", index=False)

L = ["# Selection from 1,247 incidents to 197 matched sets\n",
     "Exploratory, added after the results (DEVIATIONS.md 10). Generated by "
     "`gap_checks/selection.py`. Incident level: incidents merged into one vessel event share its "
     "stage.\n", "## Furthest stage reached\n", "| Stage | Incidents |", "| --- | --- |"]
for k, v in inc.stage.value_counts().sort_index().items():
    L.append(f"| {k} | {v} |")
e = inc[inc.stage.str.startswith("E")]
L.append(f"\nStage E reasons (incidents): {e.reason.value_counts().to_dict()}\n")

inc["analysed"] = inc.stage.str.startswith("F")
inc["confirmed"] = inc.stage.str[0].isin(list("DEF"))
for var, title in [("source", "Source"), ("setting", "Setting"), ("incident_type", "Incident type"),
                   ("vtype", "Reported vessel type"), ("region", "Region"), ("years", "Years")]:
    t = inc.groupby(var, observed=True).agg(n=("stage", "size"), confirmed=("confirmed", "mean"),
                                            analysed=("analysed", "mean"))
    t["share_all"] = t.n / len(inc)
    t["share_analysed"] = inc[inc.analysed].groupby(var, observed=True).size().reindex(t.index).fillna(0) / inc.analysed.sum()
    L.append(f"## {title}\n")
    L.append("| | Incidents | Share of all | Share of analysed | Confirmed | Analysed |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    for k, r in t.sort_values("n", ascending=False).iterrows():
        L.append(f"| {k} | {int(r.n)} | {r.share_all:.1%} | {r.share_analysed:.1%} | {r.confirmed:.1%} | {r.analysed:.1%} |")
    L.append("")
L.append("Confirmed and Analysed are the shares of that row's incidents that reached a confirmed match "
         "and a matched set. Share of analysed is the row's share among the analysed incidents.")
open("results/gap_checks/selection.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
