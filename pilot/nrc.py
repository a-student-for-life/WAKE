import pandas as pd, sys, re
f=sys.argv[1]
V=pd.read_excel(f,'VESSELS_DETAIL'); I=pd.read_excel(f,'INCIDENT_COMMONS'); M=pd.read_excel(f,'MATERIAL_INVOLVED'); C=pd.read_excel(f,'CALLS')
print('vessel rows',len(V),'unique seqnos',V.SEQNOS.nunique())
V['VESSEL_NAME']=V.VESSEL_NAME.astype(str).str.strip().str.upper()
bad=V.VESSEL_NAME.isin(['NAN','UNKNOWN','UNK','N/A','NONE','','UNKNOWN VESSEL','NA'])|V.VESSEL_NAME.str.contains('UNKNOWN|UNK ',regex=True)
V=V[~bad]; print('named',V.SEQNOS.nunique())
print(V.VESSEL_TYPE.value_counts().head(12).to_dict())
d=V.merge(I[['SEQNOS','TYPE_OF_INCIDENT','INCIDENT_CAUSE','INCIDENT_DATE_TIME','LAT_DEG','LONG_DEG','DESCRIPTION_OF_INCIDENT']],on='SEQNOS',how='left')
print(d.TYPE_OF_INCIDENT.value_counts().head(8).to_dict())
print(d.INCIDENT_CAUSE.value_counts().head(12).to_dict())
m=M.copy(); m['oil']=m.NAME_OF_MATERIAL.astype(str).str.upper().str.contains('OIL|DIESEL|FUEL|GASOLINE|HYDRAULIC|LUBE|BUNKER|PETROLEUM|CRUDE')
water=M.IF_REACHED_WATER.astype(str).str.upper().str.startswith('Y')
ok=set(m[m.oil & water].SEQNOS)
d['oilwater']=d.SEQNOS.isin(ok)
d['L']=pd.to_numeric(d.VESSEL_LENGTH,errors='coerce')
d['coords']=pd.to_numeric(d.LAT_DEG,errors='coerce').notna()
print('named & oil reached water',d[d.oilwater].SEQNOS.nunique())
print('  + coords',d[d.oilwater&d.coords].SEQNOS.nunique())
print('  + length>=65ft (or unknown length)',d[d.oilwater&((d.L>=65)|d.L.isna())].SEQNOS.nunique(),' known>=65:',d[d.oilwater&(d.L>=65)].SEQNOS.nunique())
print('length known share',d.L.notna().mean().round(2))
print('named & oil & cause', d[d.oilwater].INCIDENT_CAUSE.value_counts().head(10).to_dict())
d.to_csv(sys.argv[2],index=False)
