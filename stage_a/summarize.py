"""Write results/stageA_summary.md from the Stage A tables (every number comes from a file).

usage: python3 -I stage_a/summarize.py
"""
import os

import pandas as pd

AT_BERTH_OR_NOT_SOURCE = (r"at-berth|reporting vessel|reported the sheen|not the damaged|terminal ship|"
                          r"not a spill|is the barge|is its barge|vessel in trouble is the barge|"
                          r"source may be the facility")


def md(df):
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    out += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(out)


def main():
    inc = pd.read_csv("data/incidents.csv", dtype=str, keep_default_na=False)
    cand = pd.read_csv("data/candidates.csv", dtype=str, keep_default_na=False)
    rev = pd.read_csv("data/claude_review.csv", dtype=str, keep_default_na=False)
    status = pd.read_csv("data/match_status.csv")
    inc["year"] = inc.date_local.str[:4]

    by_year = pd.crosstab(inc.year, inc.source, margins=True, margins_name="total").reset_index()
    n_inc_cand = int((status.n_candidates.fillna(0) > 0).sum())
    auto = cand[cand.auto_reject != ""]
    to_review = cand[cand.auto_reject == ""]
    dec = rev.decision.value_counts()

    # one confirmed vessel per event: collapse yes rows with the same MMSI within 3 days
    y = rev[rev.decision == "yes"].merge(inc[["incident_id", "date_local", "source"]], on="incident_id")
    y["d"] = pd.to_datetime(y.date_local)
    y = y.sort_values(["mmsi", "d"])
    keep, last = [], {}
    for m, d in zip(y.mmsi, y.d):
        keep.append(not (m in last and (d - last[m]).days <= 3))
        last[m] = d
    events = y[keep]
    flagged = events.reason.str.contains(AT_BERTH_OR_NOT_SOURCE, case=False)
    moving = int((~flagged).sum())

    lines = [
        "# Stage A summary",
        "",
        "Generated by `stage_a/summarize.py` from `data/incidents.csv`, `data/candidates.csv`,",
        "`data/match_status.csv` and `data/claude_review.csv`.",
        "",
        "## Incidents (experiment 1)",
        "",
        f"{len(inc)} incidents, 2015–2025: {(inc.source == 'NRC').sum()} NRC, "
        f"{(inc.source == 'IncidentNews').sum()} IncidentNews.",
        "",
        md(by_year),
        "",
        "## AIS candidates (experiment 2)",
        "",
        f"All {len(status)} incidents were scanned on their UTC day and the day before. "
        f"{n_inc_cand} incidents have at least one same-name vessel in AIS, giving {len(cand)} candidates.",
        "",
        "| auto-rejection reason | candidates |",
        "| --- | --- |",
    ]
    for reason, n in auto.auto_reject.value_counts().items():
        lines.append(f"| {reason} | {n} |")
    lines += [
        f"| not auto-rejected (reviewed) | {len(to_review)} |",
        "",
        "## Claude's review",
        "",
        f"{len(rev)} candidates reviewed one by one under `stage_a/REVIEW_RULES.md`: "
        f"{dec.get('yes', 0)} yes, {dec.get('no', 0)} no, {dec.get('unsure', 0)} unsure. "
        f"At most one yes per incident ({y.incident_id.nunique()} incidents with a yes).",
        "",
        "## Projected sample",
        "",
        f"- Yes decisions collapsed to one per vessel event (same MMSI within 3 days, which merges "
        f"duplicate NRC/IncidentNews reports): **{len(events)} confirmed vessel-events** "
        f"({events.mmsi.nunique()} distinct MMSIs).",
        f"- {int(flagged.sum())} of these are flagged in their reasons as at-berth events or named vessels "
        f"that were not the source (reporting vessel, tug of a damaged barge). Without them: "
        f"**{moving} vessel-events**.",
        f"- {dec.get('unsure', 0)} unsure cases could add a few after Janice's review.",
        "",
        f"Projected number of confirmed vessels: about **{moving}–{len(events)}**, before Janice's blind "
        "review. The pilot power analysis needed about 120 vessels for 80% power at AUC 0.60 (alpha 0.01).",
        "",
        "Open questions for Janice are listed in `stage_a/ISSUES.md` (duplicates, the IncidentNews UTC "
        "window, berth cases, hurricane cases, name prefixes, the 2024 AIS host).",
    ]
    os.makedirs("results", exist_ok=True)
    open("results/stageA_summary.md", "w").write("\n".join(lines) + "\n")
    print(f"events {len(events)} moving {moving} yes {dec.get('yes', 0)}")


if __name__ == "__main__":
    main()
