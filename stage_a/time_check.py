"""Report-time convention check (ANALYSIS_PLAN.md section 3a).

usage: python3 -I stage_a/time_check.py [--confirmed data/confirmed.csv]
Without --confirmed it uses Claude's yes decisions (a preliminary run while the blind
review is under way); the official run uses the confirmed matches after adjudication.
Writes results/time_check.md and results/time_check_cases.csv.
"""
import math
import sys
from datetime import datetime
from zoneinfo import ZoneInfo

import pandas as pd

STOP_KN, STOP_MIN, NEAR_KM, MIN_CASES = 1.0, 30, 2.0, 15


def hav(a, b, c, d):
    p1, p2 = math.radians(a), math.radians(c)
    h = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(d - b) / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(min(1.0, h)))


def first_stop(tr, lat0, lon0):
    """Start of the first period with SOG < 1 kn lasting >= 30 min, within 2 km of the
    reported position. Returns a UTC timestamp or None."""
    tr = tr.assign(near=[hav(lat0, lon0, a, b) <= NEAR_KM for a, b in zip(tr.la, tr.lo)],
                   slow=tr.sog_n < STOP_KN)
    start = None
    for t, slow, near in zip(tr.t, tr.slow, tr.near):
        if slow and near:
            if start is None:
                start = t
            elif (t - start).total_seconds() / 60 >= STOP_MIN:
                return start
        else:
            start = None
    return None


def main(confirmed=None):
    inc = pd.read_csv("data/incidents.csv", dtype=str, keep_default_na=False).set_index("incident_id")
    if confirmed:
        yes = pd.read_csv(confirmed, dtype=str)
        label = f"confirmed matches in `{confirmed}`"
    else:
        r = pd.read_csv("data/claude_review.csv", dtype=str)
        yes = r[r.decision == "yes"]
        label = "Claude's yes decisions (preliminary: the blind review is not finished)"
    rows = []
    for iid, mmsi in zip(yes.incident_id, yes.mmsi):
        x = inc.loc[iid]
        if x.source != "NRC" or x.ref_method != "exact" or x.incident_type not in ("grounding", "collision_allision"):
            continue
        if not (x.date_local and x.time_local and x.tz):
            continue
        tr = pd.read_csv(f"data/tracks/{iid}_{mmsi}.csv.gz", dtype=str, keep_default_na=False)
        tr["t"] = pd.to_datetime(tr.time, errors="coerce")
        tr["la"], tr["lo"] = pd.to_numeric(tr.lat, errors="coerce"), pd.to_numeric(tr.lon, errors="coerce")
        tr["sog_n"] = pd.to_numeric(tr.sog, errors="coerce")
        tr = tr.dropna(subset=["t", "la", "lo", "sog_n"]).sort_values("t")
        stop = first_stop(tr, float(x.ref_lat), float(x.ref_lon))
        if stop is None:
            continue
        clock = datetime.strptime(f"{x.date_local} {x.time_local}", "%Y-%m-%d %H:%M")
        readings = {"local": ZoneInfo(x.tz), "eastern": ZoneInfo("America/New_York"), "utc": ZoneInfo("UTC")}
        row = dict(incident_id=iid, mmsi=mmsi, vessel=x.vessel_name, type=x.incident_type, tz=x.tz,
                   reported_clock=f"{x.date_local} {x.time_local}", ais_stop_utc=stop.strftime("%Y-%m-%d %H:%M"))
        for k, z in readings.items():
            rep = pd.Timestamp(clock.replace(tzinfo=z).astimezone(ZoneInfo("UTC"))).tz_localize(None)
            row[f"diff_h_{k}"] = round((rep - stop).total_seconds() / 3600, 2)
        rows.append(row)
    d = pd.DataFrame(rows)
    d.to_csv("results/time_check_cases.csv", index=False)
    lines = ["# Report-time check (ANALYSIS_PLAN.md section 3a)", "",
             f"Generated by `stage_a/time_check.py` from {label}.", "",
             f"Usable cases (NRC groundings and allisions with an exact position whose AIS track stops, "
             f"under {STOP_KN:g} kn for {STOP_MIN} min, within {NEAR_KM:g} km of it): **{len(d)}**.", ""]
    if len(d) == 0:
        lines.append("No usable cases.")
    else:
        lines += ["Reported time minus AIS stop time, in hours (positive = report after the stop):", "",
                  "| Reading | Median | Lower quartile | Upper quartile | Within 2 h |", "| --- | --- | --- | --- | --- |"]
        for k in ("local", "eastern", "utc"):
            s = d[f"diff_h_{k}"]
            lines.append(f"| {k} | {s.median():.2f} | {s.quantile(.25):.2f} | {s.quantile(.75):.2f} | "
                         f"{(s.abs() <= 2).sum()} of {len(s)} |")
        lines += ["", "Old rule (plan section 3a, replaced by DEVIATIONS.md #1): reading with the median closest to zero "
                  f"over all cases = {min(('local', 'eastern', 'utc'), key=lambda k: abs(d[f'diff_h_{k}'].median()))}.", ""]
        # DEVIATIONS.md #1: only cases that can tell local from Eastern, stop within 6 h
        w = d[(d.diff_h_local - d.diff_h_eastern).abs() > 0.01]
        w = w[w[["diff_h_local", "diff_h_eastern", "diff_h_utc"]].abs().min(axis=1) <= 6]
        lines += [f"Cases that can tell local from Eastern time, with the stop within 6 h of the report: **{len(w)}**.", "",
                  "| Reading | Median | Median absolute | Reports before the stop (< -0.5 h) |", "| --- | --- | --- | --- |"]
        for k in ("local", "eastern", "utc"):
            s = w[f"diff_h_{k}"]
            lines.append(f"| {k} | {s.median():.2f} | {s.abs().median():.2f} | {(s < -0.5).sum()} of {len(s)} |")
        lines += ["", "## Decision (rule in DEVIATIONS.md #1)", ""]
        if len(w) < MIN_CASES:
            lines.append(f"Fewer than {MIN_CASES} cases that can discriminate: keep local time; the check is inconclusive "
                         "on its own terms.")
            best = "local"
        else:
            best = min(("local", "eastern", "utc"), key=lambda k: w[f"diff_h_{k}"].abs().median())
        med = w[f"diff_h_{best}"].median() if len(w) else 0.0
        if len(w) >= MIN_CASES:
            lines.append(f"The reading with the smallest median absolute difference is **{best}** (median {med:+.2f} h).")
        if med > 2:
            lines.append(f"Its median is more than 2 h after the stop, so T = reported time minus {med:.2f} h.")
        else:
            lines.append(f"Its median is within 2 h, so T = the reported time read as {best} time, with no shift.")
    open("results/time_check.md", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[a.index("--confirmed") + 1] if "--confirmed" in a else None)
