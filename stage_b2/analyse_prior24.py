"""Analysis for ANALYSIS_PLAN_ADDENDUM_2.md (prior24 window), approved 15 Nov 2026.

Primary: detector 4 (off-lane) in prior24 on the M4 sets of the true date (matched on the main
window, unchanged) in which the incident vessel and at least one control are scored; pooled AUC,
permutation p (10,000, within sets, two-sided), bootstrap interval (5,000 events), seed 20261022,
one test at alpha 0.05, reading rules as the plan. Secondary (not used to read the primary):
off-lane on placebo30 and placebo60. Descriptive: the other four simple detectors in prior24, and
the distance from each vessel's median prior24 position to the event centre of the main analysis.
The GeoTrackNet secondary test is not run here (see the addendum).

usage: python3 -I stage_b2/analyse_prior24.py   (from the repository root)
writes results/stage_b2/prior24.md and prior24_tests.csv
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "stage_b"))
import analyse as A  # noqa: E402

os.chdir(ROOT)
OUT = "results/stage_b2"
os.makedirs(OUT, exist_ok=True)
W2 = "data/stage_b2/prior24/windows"
M4 = pd.read_csv("data/stage_b/matched/M4.csv.gz")
ev = pd.read_csv("data/stage_b/events.csv")
main_ids = set(ev.event_id[ev.main_exclude.astype(str).str.lower() == "false"])
files = sorted(glob.glob(os.path.join(W2, "*.csv.gz")))
w = pd.concat([pd.read_csv(f, usecols=A.WCOLS + ["med_lat", "med_lon"]) for f in files], ignore_index=True)
w["candidate_excluded"] = w.candidate_excluded.astype(bool)
w["is_incident"] = w.is_incident.astype(bool)


def hav(a, b, c, d):
    a, b, c, d = map(np.radians, (a, b, c, d))
    h = np.sin((c - a) / 2) ** 2 + np.cos(a) * np.cos(c) * np.sin((d - b) / 2) ** 2
    return 2 * 6371.0 * np.arcsin(np.sqrt(h))


rows, L = [], ["# prior24: where incident vessels were the day before (ANALYSIS_PLAN_ADDENDUM_2.md)\n",
               f"Window files: {len(files)}. Generated by `stage_b2/analyse_prior24.py`.\n"]
for sc in ["real", "placebo30", "placebo60"]:
    mm = M4[(M4.scenario == sc) & M4.event_id.isin(main_ids)]
    have = set(w[w.scenario == sc].event_id)
    mm = mm[mm.event_id.isin(have)]
    if mm.empty:
        continue
    mem = A.members_for(mm, w[w.scenario == sc], "main")
    for d in A.DET:
        primary = sc == "real" and d == "d4_off_lane"
        r = A.auc_test(A.set_arrays(mem, d), perm=primary or d == "d4_off_lane", boot=True)
        r.update(scenario=sc, detector=d, role="primary" if primary else
                 ("secondary" if d == "d4_off_lane" else "descriptive"),
                 sets_available=mm.event_id.nunique(),
                 members_unscored=int(mem[d].isna().sum()), members=len(mem))
        rows.append(r)
out = pd.DataFrame(rows)
out.to_csv(os.path.join(OUT, "prior24_tests.csv"), index=False)

p = out[(out.scenario == "real") & (out.detector == "d4_off_lane")].iloc[0]
if p.p < 0.05 and p.auc >= 0.60:
    reading = "useful signal"
elif p.hi < 0.60:
    reading = "no useful signal"
else:
    reading = "inconclusive"
L += ["## Primary test (off-lane, prior24, true date)\n",
      f"Sets {int(p.n_sets)} (of {int(p.sets_available)} with an M4 set and a prior24 file), pairs {int(p.n_pairs)}: "
      f"AUC {p.auc:.3f} (95% interval {p.lo:.3f}-{p.hi:.3f}), permutation p {p.p:.4f}. Reading: **{reading}**.\n",
      "## All results\n", "| Scenario | Detector | Role | Sets | Pairs | AUC | 95% interval | Perm. p | Members unscored |",
      "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
for r in out.itertuples():
    L.append(f"| {r.scenario} | {A.DNAME[r.detector]} | {r.role} | {r.n_sets} | {r.n_pairs} | {r.auc:.3f} | "
             f"{r.lo:.3f}-{r.hi:.3f} | {'' if pd.isna(r.p) else f'{r.p:.4f}'} | {r.members_unscored} of {r.members} |")

# descriptive: distance from the main-analysis centre
c0 = pd.concat([pd.read_csv(f, usecols=["event_id", "scenario", "centre_lat", "centre_lon"]).iloc[:1]
                for f in glob.glob("data/stage_b/windows/*_real.csv.gz")])
mm = M4[(M4.scenario == "real") & M4.event_id.isin(main_ids)][["event_id", "mmsi", "role"]]
x = mm.merge(w[w.scenario == "real"][["event_id", "mmsi", "med_lat", "med_lon"]], on=["event_id", "mmsi"])
x = x.merge(c0[["event_id", "centre_lat", "centre_lon"]], on="event_id").dropna(subset=["med_lat"])
x["km"] = hav(x.centre_lat, x.centre_lon, x.med_lat, x.med_lon)
g = x.groupby("role").km
L += ["\n## Distance of the median prior24 position from the main-analysis centre (true date)\n",
      "| Role | Vessels | Median km | IQR |", "| --- | --- | --- | --- |"]
for role, s in g:
    L.append(f"| {role} | {len(s)} | {s.median():.1f} | {s.quantile(.25):.1f}-{s.quantile(.75):.1f} |")
x[["event_id", "mmsi", "role", "km"]].to_csv(os.path.join(OUT, "prior24_distance.csv"), index=False)
open(os.path.join(OUT, "prior24.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
