"""Analysis for ANALYSIS_PLAN_ADDENDUM_3.md (six-hour slices), approved 15 Nov 2026.

Primary (one test): detector 4 (off-lane) in s24 = [T-24 h, T-18 h) on the published M4 sets of
the true date for the NRC-timed events, sets in which the incident vessel and at least one control
are scored; pooled AUC, permutation p (10,000, within sets, two-sided), bootstrap interval (5,000
events), seed 20261022, reading rules as the plan. Descriptive: all five detectors in all four
slices; s6 minus s24 per detector with a bootstrap over events (sets scored in both slices).
Checks: the recomputed main window against the published main-window scores for the same
vessels; an independent recomputation of the primary AUC.

usage: python3 -I stage_b3/analyse_slices.py   (from the repository root)
writes results/stage_b3/slices.md, slices_tests.csv, slices_diff.csv
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "stage_b"))
import analyse as A  # noqa: E402

os.chdir(ROOT)
OUT = "results/stage_b3"
os.makedirs(OUT, exist_ok=True)
D3 = "data/stage_b3/slices"
SL = ["s24", "s18", "s12", "s6"]
LAB = {"s24": "T-24 to T-18 h", "s18": "T-18 to T-12 h", "s12": "T-12 to T-6 h", "s6": "T-6 h to T"}
ev = pd.read_csv(os.path.join(D3, "events.csv"))
files = sorted(glob.glob(os.path.join(D3, "windows", "*.csv.gz")))
w = pd.concat([pd.read_csv(f, usecols=A.WCOLS) for f in files], ignore_index=True)
w["candidate_excluded"] = w.candidate_excluded.astype(bool)
w["is_incident"] = w.is_incident.astype(bool)
M4 = pd.read_csv("data/stage_b/matched/M4.csv.gz")
mm = M4[(M4.scenario == "real") & M4.event_id.isin(set(w.event_id))]

# 1. reproduction check: recomputed main window vs published main window, same vessels
w0 = A.load_windows()
w0 = w0[(w0.scenario == "real") & (w0.window == "main") & w0.event_id.isin(set(w.event_id))]
c = w[w.window == "main"].merge(w0, on=["event_id", "scenario", "window", "mmsi"], suffixes=("", "_pub"))
c = c[c.mmsi.isin(mm.mmsi) | c.is_incident]
repro = {d: float(np.nanmax(np.abs(c[d] - c[d + "_pub"]))) if len(c) else np.nan for d in A.DET}
nan_mismatch = {d: int((c[d].isna() != c[d + "_pub"].isna()).sum()) for d in A.DET}

# 2. tests
rows, arrays = [], {}
for win in ["main"] + SL:
    mem = A.members_for(mm, w, win)
    for d in A.DET:
        sets = A.set_arrays(mem, d)
        arrays[(win, d)] = sets
        primary = win == "s24" and d == "d4_off_lane"
        r = A.auc_test(sets, perm=primary, boot=True)
        r.update(window=win, detector=d, role="primary" if primary else "descriptive",
                 members=len(mem), members_unscored=int(mem[d].isna().sum()))
        rows.append(r)
out = pd.DataFrame(rows)
out.to_csv(os.path.join(OUT, "slices_tests.csv"), index=False)

# 3. s6 minus s24 per detector, bootstrap over events on sets scored in both
diffs = []
for d in A.DET:
    a = {s[0]: (s[1][s[2]], s[3]) for s in arrays[("s6", d)]}
    b = {s[0]: (s[1][s[2]], s[3]) for s in arrays[("s24", d)]}
    ids = sorted(set(a) & set(b))
    wa, na = np.array([a[i][0] for i in ids]), np.array([a[i][1] for i in ids], float)
    wb, nb = np.array([b[i][0] for i in ids]), np.array([b[i][1] for i in ids], float)
    obs = wa.sum() / na.sum() - wb.sum() / nb.sum()
    rng = np.random.default_rng(A.SEED)
    idx = rng.integers(0, len(ids), (A.NBOOT, len(ids)))
    bs = wa[idx].sum(1) / na[idx].sum(1) - wb[idx].sum(1) / nb[idx].sum(1)
    diffs.append(dict(detector=d, sets=len(ids), auc_s6=wa.sum() / na.sum(), auc_s24=wb.sum() / nb.sum(),
                      diff=obs, lo=np.percentile(bs, 2.5), hi=np.percentile(bs, 97.5)))
diffs = pd.DataFrame(diffs)
diffs.to_csv(os.path.join(OUT, "slices_diff.csv"), index=False)

# 4. independent recomputation of the primary AUC (plain pair counting)
mem = A.members_for(mm, w, "s24").dropna(subset=["d4_off_lane"])
num = den = 0.0
for _, g in mem.groupby("set_id"):
    inc, ctl = g[g.role == "incident"].d4_off_lane.to_numpy(), g[g.role == "control"].d4_off_lane.to_numpy()
    if len(inc) == 1 and len(ctl):
        num += (inc[0] > ctl).sum() + 0.5 * (inc[0] == ctl).sum()
        den += len(ctl)
indep = num / den

p = out[out.role == "primary"].iloc[0]
reading = ("useful signal" if (p.p < 0.05 and p.auc >= 0.60) else
           "no useful signal" if p.hi < 0.60 else "inconclusive")
L = ["# Six-hour slices of the last day (ANALYSIS_PLAN_ADDENDUM_3.md)\n",
     f"Generated by `stage_b3/analyse_slices.py`. NRC-timed events {len(ev)}; window files {len(files)}; "
     f"M4 sets {mm.event_id.nunique()}.\n",
     "## Primary test (off-lane, s24 = T-24 to T-18 h, true date)\n",
     f"Sets {int(p.n_sets)}, pairs {int(p.n_pairs)}: AUC {p.auc:.3f} (95% interval {p.lo:.3f}-{p.hi:.3f}), "
     f"permutation p {p.p:.4f}. Reading: **{reading}**. Independent recomputation: {indep:.4f}.\n",
     "## All slices (pooled AUC, 95% bootstrap interval)\n",
     "| Window | Sets (off-lane) | " + " | ".join(A.DNAME[d] for d in A.DET) + " |",
     "| --- | --- |" + " --- |" * len(A.DET)]
for win in ["main"] + SL:
    g = out[out.window == win].set_index("detector")
    L.append(f"| {LAB.get(win, 'main T-24 h to T')} | {int(g.n_sets['d4_off_lane'])} | " + " | ".join(
        f"{g.auc[d]:.3f} ({g.lo[d]:.3f}-{g.hi[d]:.3f})" for d in A.DET) + " |")
L += ["\n## Last slice minus first slice (s6 - s24), sets scored in both\n",
      "| Detector | Sets | s6 | s24 | Difference | 95% interval |", "| --- | --- | --- | --- | --- | --- |"]
for r in diffs.itertuples():
    L.append(f"| {A.DNAME[r.detector]} | {r.sets} | {r.auc_s6:.3f} | {r.auc_s24:.3f} | {r.diff:+.3f} | "
             f"{r.lo:+.3f} to {r.hi:+.3f} |")
L += ["\n## Reproduction check (recomputed main window vs published, matched vessels)\n",
      f"Vessel rows compared {len(c)}; largest absolute difference per detector {repro}; "
      f"scored/unscored mismatches {nan_mismatch}.\n"]
open(os.path.join(OUT, "slices.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
